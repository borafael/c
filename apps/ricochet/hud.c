static const uint8_t *glyph(char c) {
    static const uint8_t COLON[7] = {0x00,0x0C,0x0C,0x00,0x0C,0x0C,0x00};
    static const uint8_t DASH[7]  = {0x00,0x00,0x00,0x1F,0x00,0x00,0x00};
    static const uint8_t SLASH[7] = {0x01,0x02,0x02,0x04,0x08,0x08,0x10};
    static const uint8_t BANG[7]  = {0x04,0x04,0x04,0x04,0x04,0x00,0x04};
    static const uint8_t DOT[7]   = {0x00,0x00,0x00,0x00,0x00,0x0C,0x0C};
    static const uint8_t PCT[7]   = {0x18,0x19,0x02,0x04,0x08,0x13,0x03};
    static const uint8_t LT[7]    = {0x02,0x04,0x08,0x10,0x08,0x04,0x02};
    static const uint8_t GT[7]    = {0x08,0x04,0x02,0x01,0x02,0x04,0x08};
    if (c >= '0' && c <= '9') return FONT_DIGITS[c - '0'];
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return FONT_ALPHA[c - 'A'];
    switch (c) {
    case ':': return COLON;
    case '-': return DASH;
    case '/': return SLASH;
    case '!': return BANG;
    case '.': return DOT;
    case '%': return PCT;
    case '<': return LT;
    case '>': return GT;
    default:  return NULL;
    }
}

static void put(hud_target t, int x, int y, uint32_t c) {
    if (x >= 0 && y >= 0 && x < t.w && y < t.h) t.px[y * t.w + x] = c;
}

int hud_text_width(const char *s, int scale) {
    int n = (int)strlen(s);
    return n > 0 ? (n * 6 - 1) * scale : 0;
}

static void text_raw(hud_target t, int x, int y, const char *s, int scale, uint32_t c) {
    for (; *s; s++, x += 6 * scale) {
        const uint8_t *g = glyph(*s);
        if (!g) continue;
        for (int r = 0; r < 7; r++)
            for (int col = 0; col < 5; col++) {
                if (!(g[r] & (1u << (4 - col)))) continue;
                for (int dy = 0; dy < scale; dy++)
                    for (int dx = 0; dx < scale; dx++)
                        put(t, x + col * scale + dx, y + r * scale + dy, c);
            }
    }
}

void hud_text(hud_target t, int x, int y, const char *s, int scale, uint32_t argb) {
    int sh = scale > 1 ? scale / 2 : 1;
    text_raw(t, x + sh, y + sh, s, scale, 0xFF000000u);
    text_raw(t, x, y, s, scale, argb);
}

void hud_text_center(hud_target t, int cy, const char *s, int scale, uint32_t argb) {
    hud_text(t, (t.w - hud_text_width(s, scale)) / 2, cy - 7 * scale / 2, s, scale, argb);
}

void hud_rect(hud_target t, int x, int y, int w, int h, uint32_t argb) {
    for (int j = y; j < y + h; j++)
        for (int i = x; i < x + w; i++) put(t, i, j, argb);
}

static uint32_t mix(uint32_t dst, uint32_t rgb, float a) {
    int r = (int)(((dst >> 16) & 255) * (1 - a) + ((rgb >> 16) & 255) * a);
    int g = (int)(((dst >> 8) & 255) * (1 - a) + ((rgb >> 8) & 255) * a);
    int b = (int)((dst & 255) * (1 - a) + (rgb & 255) * a);
    return 0xFF000000u | (uint32_t)(r << 16) | (uint32_t)(g << 8) | (uint32_t)b;
}

void hud_blend_rect(hud_target t, int x, int y, int w, int h, uint32_t rgb, float a) {
    for (int j = y; j < y + h; j++) {
        if (j < 0 || j >= t.h) continue;
        for (int i = x; i < x + w; i++) {
            if (i < 0 || i >= t.w) continue;
            t.px[j * t.w + i] = mix(t.px[j * t.w + i], rgb, a);
        }
    }
}

void hud_circle(hud_target t, int cx, int cy, int r, uint32_t argb, int filled) {
    int r2o = r * r + r, r2i = (r - 1) * (r - 1) - (r - 1);
    for (int y = -r; y <= r; y++)
        for (int x = -r; x <= r; x++) {
            int d = x * x + y * y;
            if (d > r2o) continue;
            if (!filled && d < r2i) continue;
            put(t, cx + x, cy + y, argb);
        }
}

void hud_tint(hud_target t, uint32_t rgb, float a) {
    if (a <= 0.0f) return;
    if (a > 1.0f) a = 1.0f;
    for (int i = 0; i < t.w * t.h; i++) t.px[i] = mix(t.px[i], rgb, a);
}
